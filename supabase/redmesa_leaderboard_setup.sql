-- Run this in Supabase SQL editor.
-- Online leaderboard for Red Mesa Rally: one best time per signed-in arcade user per event.
-- Times are only written through redmesa_submit_time(), which keeps the faster time and takes
-- the username from arcade_profiles, so nobody can post under another name.

begin;

create table if not exists public.redmesa_leaderboard (
  id bigint generated by default as identity primary key,
  event_id text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  username text not null,
  vehicle text,
  time_ms integer not null,
  best_lap_ms integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint redmesa_leaderboard_event_format check (event_id ~ '^[a-z0-9-]{2,32}$'),
  constraint redmesa_leaderboard_time_range check (time_ms between 5000 and 3600000),
  constraint redmesa_leaderboard_one_per_user unique (event_id, user_id)
);

create index if not exists redmesa_leaderboard_event_time_idx
on public.redmesa_leaderboard (event_id, time_ms asc, updated_at asc);

alter table public.redmesa_leaderboard enable row level security;

drop policy if exists "redmesa leaderboard is readable" on public.redmesa_leaderboard;
create policy "redmesa leaderboard is readable"
on public.redmesa_leaderboard
for select
using (true);

-- No insert/update policies: writes go through the function below.

create or replace function public.redmesa_submit_time(
  p_event_id text,
  p_time_ms integer,
  p_vehicle text default null,
  p_best_lap_ms integer default null
)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  uname text;
  changed integer;
  my_best integer;
  my_rank integer;
begin
  if uid is null then
    raise exception 'sign in required';
  end if;

  select p.username into uname from public.arcade_profiles p where p.id = uid;
  if uname is null then
    select coalesce(nullif(trim(u.raw_user_meta_data->>'username'), ''), split_part(u.email, '@', 1), 'Player')
    into uname from auth.users u where u.id = uid;
  end if;

  insert into public.redmesa_leaderboard (event_id, user_id, username, vehicle, time_ms, best_lap_ms)
  values (p_event_id, uid, left(uname, 24), left(p_vehicle, 24), p_time_ms, p_best_lap_ms)
  on conflict (event_id, user_id) do update
    set time_ms = excluded.time_ms,
        best_lap_ms = excluded.best_lap_ms,
        vehicle = excluded.vehicle,
        username = excluded.username,
        updated_at = now()
    where excluded.time_ms < public.redmesa_leaderboard.time_ms;
  get diagnostics changed = row_count;

  select l.time_ms into my_best from public.redmesa_leaderboard l where l.event_id = p_event_id and l.user_id = uid;
  select count(*) + 1 into my_rank from public.redmesa_leaderboard l where l.event_id = p_event_id and l.time_ms < my_best;

  return json_build_object('improved', changed > 0, 'best_ms', my_best, 'rank', my_rank);
end;
$$;

revoke all on function public.redmesa_submit_time(text, integer, text, integer) from public, anon;
grant execute on function public.redmesa_submit_time(text, integer, text, integer) to authenticated;

commit;
